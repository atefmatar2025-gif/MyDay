                storePassword = System.getenv("MYDAY_KEYSTORE_PASSWORD")
                keyAlias = System.getenv("MYDAY_KEY_ALIAS")
                keyPassword = System.getenv("MYDAY_KEY_PASSWORD")
            } else {
                val debug = getByName("debug")
                storeFile = debug.storeFile
                storePassword = debug.storePassword
                keyAlias = debug.keyAlias
                keyPassword = debug.keyPassword
            }
        }
