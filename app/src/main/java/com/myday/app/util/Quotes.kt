    /** نختار بخطوة متباعدة حتى تتنوع الأنواع من يوم لآخر، وكل العبارات تمر قبل أي تكرار. */
    fun forDate(date: LocalDate): String {
        val n = list.size
        var step = 37
        while (gcd(step, n) != 1) step++
        val day = Math.floorMod(date.toEpochDay(), n.toLong()).toInt()
        return list[(day * step) % n]
    }

    private tailrec fun gcd(a: Int, b: Int): Int = if (b == 0) a else gcd(b, a % b)

    val count: Int get() = list.size
